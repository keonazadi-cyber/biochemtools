#!/usr/bin/env python3
"""Genetics on one page: the four crosses, Hardy-Weinberg, ABO, X-linked.

Genetics is a practice subject with 30 questions and, until this, one chart
(blood type inheritance). The pages it covers carry the site's best Bing demand:
punnett-square-calculator 1.4K impressions, hardy-weinberg 1.1K,
blood-type-punnett-square 719, x-linked-inheritance 195, dihybrid-cross 178.

Nothing here is typed from memory. The Punnett squares are generated by running
punnett-square-calculator.html's own genes/gametes/canon/pheno/ratio functions in
node; the ABO table by running blood-type-punnett-square-calculator.html's own
GENO/cross/tally/pheno; the X-linked split by running
x-linked-inheritance-calculator.html's own femaleStatus/maleStatus. The equations,
the five Hardy-Weinberg assumptions and the three common mistakes are parsed out
of the pages that teach them. If a page changes, this build fails rather than
shipping a chart that disagrees with the site.

Colour carries meaning and nothing else: BLUE is the dominant phenotype or
allele, PURPLE the recessive one, GREEN a formula or the asserted answer, RED the
common-mistake strip, AMBER section headings only.
"""
import json
import os as _os
import re
import subprocess
import sys

from PIL import Image, ImageDraw

sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
import chartkit
from lightmode import theme, suffix

HERE = _os.path.dirname(_os.path.abspath(__file__))
SITE = _os.path.join(HERE, "..", "..")
BUILD_DIR = _os.path.join(HERE, "build")
_os.makedirs(BUILD_DIR, exist_ok=True)

LIGHT, P = theme()
F = chartkit.fonts()
W, M = chartkit.WIDTH, chartkit.MARGIN
CW = W - 2 * M


def page(name):
    return open(_os.path.join(SITE, name), encoding="utf-8").read()


def js_func(src, name):
    """Lift one function out of a page's script, braces matched."""
    i = src.index("function %s(" % name)
    j = src.index("{", i)
    depth = 0
    for k in range(j, len(src)):
        if src[k] == "{":
            depth += 1
        elif src[k] == "}":
            depth -= 1
            if depth == 0:
                return src[i:k + 1]
    raise RuntimeError("unbalanced braces reading %s()" % name)


def node(code):
    r = subprocess.run(["node", "-e", code], capture_output=True, text=True)
    assert r.returncode == 0, "node failed: %s" % r.stderr.strip()
    return json.loads(r.stdout)


# --- 1. the crosses: run the Punnett page's own functions -------------------
PUN = page("punnett-square-calculator.html")
_pun_lib = "\n".join(js_func(PUN, n) for n in
                     ("genes", "gametes", "canon", "pheno", "gcd", "ratio"))
SQ = node(_pun_lib + """
function sq(a,b){
 const g1=genes(a), g2=genes(b), n=g1.length;
 const ga1=gametes(g1), ga2=gametes(g2);
 const rows=[], geno={}, phe={};
 for(const r of ga1){ const row=[];
  for(const c of ga2){ const gt=canon((r+c).split(""));
   const ph=pheno(gt,n);
   row.push([gt, !/[a-z]/.test(ph)]);      // true = shows every dominant trait
   geno[gt]=(geno[gt]||0)+1; phe[ph]=(phe[ph]||0)+1; }
  rows.push(row); }
 return {top:ga2, side:ga1, rows,
         geno:ratio(geno), pheno:ratio(phe), total:ga1.length*ga2.length};
}
const out={};
for(const [a,b] of [["Aa","Aa"],["Aa","aa"],["AA","aa"],["AaBb","AaBb"]])
 out[a+"x"+b]=sq(a,b);
console.log(JSON.stringify(out));
""")


def ratio_str(pairs):
    return " : ".join(str(r) for _, r, _ in pairs)


def classes(pairs):
    return " ".join(k for k, _, _ in pairs)


assert ratio_str(SQ["AaxAa"]["geno"]) == "2 : 1 : 1", SQ["AaxAa"]["geno"]
assert sorted(k for k, _, _ in SQ["AaxAa"]["geno"]) == ["AA", "Aa", "aa"]
assert ratio_str(SQ["AaxAa"]["pheno"]) == "3 : 1", SQ["AaxAa"]["pheno"]
assert ratio_str(SQ["Aaxaa"]["geno"]) == "1 : 1", SQ["Aaxaa"]["geno"]
assert ratio_str(SQ["Aaxaa"]["pheno"]) == "1 : 1", SQ["Aaxaa"]["pheno"]
assert SQ["Aaxaa"]["total"] == 2 and len(SQ["Aaxaa"]["top"]) == 1, \
    "aa must make one kind of gamete, so the grid is 2 x 1"
assert SQ["AAxaa"]["total"] == 1 and classes(SQ["AAxaa"]["pheno"]) == "A_", \
    "AA x aa must give nothing but the dominant phenotype"
assert ratio_str(SQ["AaBbxAaBb"]["pheno"]) == "9 : 3 : 3 : 1", SQ["AaBbxAaBb"]["pheno"]
assert classes(SQ["AaBbxAaBb"]["pheno"]) == "A_B_ A_bb aaB_ aabb"
assert SQ["AaBbxAaBb"]["total"] == 16 and len(SQ["AaBbxAaBb"]["geno"]) == 9, \
    "16 boxes, 9 distinct genotypes"
assert SQ["AaBbxAaBb"]["geno"][0][:2] == ["AaBb", 4], SQ["AaBbxAaBb"]["geno"][0]
assert sum(1 for row in SQ["AaBbxAaBb"]["rows"] for _, dom in row if dom) == 9

DIH = page("dihybrid-cross-calculator.html")
assert 'console.assert(run("AaBb","AaBb")==="9:3:3:1"' in DIH, \
    "the dihybrid page no longer self-checks 9:3:3:1"

# the genotype-vs-phenotype correction, in the site's own words
assert "The 3:1 figure is the phenotype ratio" in PUN, \
    "the genotype/phenotype warning is gone from the Punnett page"

# --- 2. Hardy-Weinberg, parsed off the page that teaches it -----------------
HW = page("hardy-weinberg-calculator.html")
assert "p + q = 1" in HW and "p² + 2pq + q² = 1" in HW, \
    "the Hardy-Weinberg equations changed on the page"
TERMS = []
for label, term in re.findall(
        r"(homozygous dominant|heterozygous|homozygous recessive)\s*\((\w+)\)", HW):
    if (label, term) not in TERMS:
        TERMS.append((label, term))
assert TERMS == [("homozygous dominant", "AA"), ("heterozygous", "Aa"),
                 ("homozygous recessive", "aa")], TERMS
m = re.search(r"assumptions is violated: ([^<.]*)\.", HW)
assert m, "the five-assumptions sentence is gone from the Hardy-Weinberg page"
ASSUME = [a.strip() for a in m.group(1).split(", ")]
assert len(ASSUME) == 5, ASSUME
assert ASSUME[0] == "no mutation" and ASSUME[1] == "random mating", ASSUME
assert "critical value 3.84 for 1 degree of freedom" in HW, \
    "the chi-square critical value changed"
assert "the carrier fraction is the 2pq term, not q and not q squared" in HW, \
    "the p-squared carrier warning is gone"
assert "The 2 counts the two parental orders" in HW, \
    "the 2pq explanation is gone"

# --- 3. ABO, generated by the blood type page's own cross/tally/pheno -------
BT = page("blood-type-punnett-square-calculator.html")
_geno_line = re.search(r"const GENO=\{[^}]*\};", BT)
assert _geno_line, "GENO not found on the blood type page"
GENO = dict(re.findall(r"(\w+):\[([^\]]*)\]", _geno_line.group(0)))
GENO = {k: [g.strip('"') for g in v.split(",")] for k, v in GENO.items()}
assert GENO == {"A": ["AA", "AO"], "B": ["BB", "BO"],
                "AB": ["AB"], "O": ["OO"]}, GENO
_types_line = re.search(r"const TYPES=\[[^\]]*\];", BT).group(0)
ABO = node(_geno_line.group(0) + "\n" + _types_line + "\n"
           + "\n".join(js_func(BT, n) for n in ("pheno", "alleles", "cross", "tally"))
           + """
const out={};
for(const s1 of TYPES) for(const s2 of TYPES){
 const combos=[];
 for(const g1 of GENO[s1]) for(const g2 of GENO[s2])
  combos.push(tally(cross(g1,g2)));
 const possible=TYPES.filter(t=>combos.some(c=>c[t]));
 out[s1+"x"+s2]={possible, impossible:TYPES.filter(t=>!possible.includes(t))};
}
console.log(JSON.stringify(out));
""")
TYPES = ["A", "B", "AB", "O"]
PAIRS = [(a, b) for i, a in enumerate(TYPES) for b in TYPES[i:]]
assert len(PAIRS) == 10, PAIRS
for a, b in PAIRS:                       # the model must not care about order
    assert ABO["%sx%s" % (a, b)] == ABO["%sx%s" % (b, a)], (a, b)
ALL_FOUR = [(a, b) for a, b in PAIRS if len(ABO["%sx%s" % (a, b)]["possible"]) == 4]
assert ALL_FOUR == [("A", "B")], \
    "A x B must be the only pairing that can give all four child types, got %s" % ALL_FOUR
assert ABO["ABxO"]["possible"] == ["A", "B"], ABO["ABxO"]
assert ABO["OxO"]["possible"] == ["O"], ABO["OxO"]
assert ABO["AxA"]["possible"] == ["A", "O"], ABO["AxA"]
assert ABO["ABxAB"]["impossible"] == ["O"], ABO["ABxAB"]

# --- 4. X-linked, generated by the X-linked page's own status functions -----
XL = page("x-linked-inheritance-calculator.html")
XLR = node('let mode="rec";\n'
           + "\n".join(js_func(XL, n) for n in ("femaleStatus", "maleStatus"))
           + """
const mom="Hh", dad="HY";              // carrier mother x unaffected father
const mA=[mom[0],mom[1]], dX=dad[0];
console.log(JSON.stringify({
 dX,
 daughters: mA.map(a=>({mom:a, dad:dX, status:femaleStatus(a,dX)})),
 sons:      mA.map(a=>({mom:a, status:maleStatus(a)})),
}));
""")
assert XLR["dX"] == "H", XLR
assert [d["status"] for d in XLR["daughters"]] == ["unaffected", "carrier"], XLR
assert [s["status"] for s in XLR["sons"]] == ["unaffected", "affected"], XLR
assert "a son needs one mutant allele to be affected, a daughter needs two" in XL, \
    "the recessive X-linked rule changed on the page"

# --- what goes on the page --------------------------------------------------
DOM, REC = P["BLUE"], P["PURPLE"]

CROSSES = [
    ("AaxAa", "Aa × Aa", 104, 58,
     ["genotype   %s   (AA : Aa : aa)" % " : ".join(
         str(r) for _, r, _ in sorted(SQ["AaxAa"]["geno"], key=lambda t: t[0] != "AA")),
      "phenotype  %s   AA and Aa alike" % ratio_str(SQ["AaxAa"]["pheno"])]),
    ("Aaxaa", "Aa × aa", 104, 58,
     ["genotype %s, phenotype %s" % (ratio_str(SQ["Aaxaa"]["geno"]),
                                     ratio_str(SQ["Aaxaa"]["pheno"])),
      "test cross: unknown was Aa"]),
    ("AAxaa", "AA × aa", 104, 58,
     ["every child %s" % classes(SQ["AAxaa"]["pheno"]),
      "test cross: unknown was AA"]),
    ("AaBbxAaBb", "AaBb × AaBb", 88, 58,
     ["phenotype  %s   over %d boxes" % (ratio_str(SQ["AaBbxAaBb"]["pheno"]),
                                         SQ["AaBbxAaBb"]["total"]),
      "%d distinct genotypes, AaBb in %d boxes" % (len(SQ["AaBbxAaBb"]["geno"]),
                                                   SQ["AaBbxAaBb"]["geno"][0][1])]),
]

HW_ROWS = [
    ("p + q = 1", "the two allele frequencies"),
    ("p² + 2pq + q² = 1", "the three genotype frequencies"),
    ("p²", "%s (%s)" % TERMS[0][::-1]),
    ("2pq", "%s (%s), the carriers" % TERMS[1][::-1]),
    ("q²", "%s (%s), the affected" % TERMS[2][::-1]),
    ("q = √(q²)", "start from the recessive phenotype, then p = 1 - q"),
]

MISTAKES = [
    ("1 : 2 : 1 is not 3 : 1",
     "1 : 2 : 1 is the GENOTYPE ratio of Aa × Aa. 3 : 1 is the phenotype "
     "ratio, because AA and Aa look alike."),
    ("p² is not the carriers",
     "Carriers are heterozygous, so the carrier share is 2pq. p² is the "
     "homozygous dominant share and q² the affected share."),
    ("2pq does not mean twice as common",
     "The 2 counts the two parental orders that both give Aa, A from either "
     "parent. It is not a claim that heterozygotes are twice as common."),
]


def draw():
    H = 2600
    img = Image.new("RGB", (W, H), P["BG"])
    d = ImageDraw.Draw(img)
    T = chartkit.safe_text
    y = M

    def fits(s, font, limit, where):
        w = d.textlength(s, font=font)
        assert w <= limit, "%s overflows by %dpx: %r" % (where, w - limit, s[:50])
        return w

    T(d, (M, y), "Genetics, one page", F["title"], P["WHITE"])
    y += 70
    sub = ("The crosses, Hardy-Weinberg, ABO and X-linked inheritance, "
           "every square generated by the site's own calculators.")
    fits(sub, F["sub"], CW, "subtitle")
    T(d, (M, y), sub, F["sub"], P["GRAY"])
    y += 56

    def band(title):
        nonlocal y
        d.rectangle([M, y, W - M, y + 2], fill=P["LINE"])
        y += 18
        T(d, (M, y), title, F["head"], P["AMBER"])
        y += 42

    def punnett(x, y0, top, side, rows, cell, hdr):
        """One square, drawn with rectangles. Returns its width and height."""
        for j, g in enumerate(top):
            cx = x + hdr + j * cell
            d.rectangle([cx, y0, cx + cell, y0 + hdr], fill=P["BAND"],
                        outline=P["LINE"])
            T(d, (cx + (cell - d.textlength(g, font=F["label"])) / 2, y0 + 16),
              g, F["label"], P["GRAY"])
        for i, g in enumerate(side):
            cy = y0 + hdr + i * cell
            d.rectangle([x, cy, x + hdr, cy + cell], fill=P["BAND"],
                        outline=P["LINE"])
            T(d, (x + (hdr - d.textlength(g, font=F["label"])) / 2,
                  cy + (cell - 24) / 2), g, F["label"], P["GRAY"])
        for i, row in enumerate(rows):
            for j, (gt, dom) in enumerate(row):
                cx, cy = x + hdr + j * cell, y0 + hdr + i * cell
                d.rectangle([cx, cy, cx + cell, cy + cell], fill=P["CHIP"],
                            outline=P["LINE"])
                w = d.textlength(gt, font=F["label"])
                assert w < cell - 8, "genotype %r does not fit a %dpx cell" % (gt, cell)
                T(d, (cx + (cell - w) / 2, cy + (cell - 24) / 2), gt,
                  F["label"], DOM if dom else REC)
        return hdr + len(top) * cell, hdr + len(rows) * cell

    # --- the crosses, the visual anchor ---
    band("The crosses that matter")
    widths = [58 + len(SQ[k]["top"]) * c for k, _, c, _, _ in
              [(k, lb, c, h, cap) for k, lb, c, h, cap in CROSSES]]
    gap = (CW - sum(widths)) / (len(CROSSES) - 1)
    assert gap > 40, "the four squares do not fit on one row"
    tall = max(58 + len(SQ[k]["rows"]) * c for k, _, c, _, _ in CROSSES)
    xs, x = [], float(M)
    for wid in widths:
        xs.append(x)
        x += wid + gap
    label_y, grid_y = y, y + 38
    for (key, lab, cell, hdr, caption), x0, wid in zip(CROSSES, xs, widths):
        limit = wid + gap - 24
        fits(lab, F["head"], limit, "cross label %r" % lab)
        T(d, (x0, label_y), lab, F["head"], P["WHITE"])
        punnett(x0, grid_y, SQ[key]["top"], SQ[key]["side"], SQ[key]["rows"],
                cell, hdr)
        cy = grid_y + tall + 16
        for line in caption:
            fits(line, F["small"], limit, "caption under %r" % lab)
            T(d, (x0, cy), line, F["small"], P["GRAY"])
            cy += 28
    y = grid_y + tall + 16 + 28 * 2 + 10
    T(d, (M, y), "A homozygous parent makes one kind of gamete, so its column "
                 "collapses: Aa × aa is a 2 × 1 grid, not 2 × 2.",
      F["body"], P["GRAY"])
    y += 46

    # --- Hardy-Weinberg ---
    band("Hardy-Weinberg")
    hw_y = y
    for term, meaning in HW_ROWS:
        T(d, (M, y), term, F["label"], P["GREEN"])
        T(d, (M + 190, y), meaning, F["body"], P["GRAY"])
        y += 38
    y += 2
    T(d, (M, y), "With real counts: p = (2 × AA + Aa) / 2N, then chi-square "
                 "against 3.84 at 1 degree of freedom.", F["body"], P["GRAY"])
    ay = hw_y
    ax = M + 820
    T(d, (ax, ay), "The five assumptions, all of them \"nothing is changing\"",
      F["label"], P["WHITE"])
    ay += 34
    for i, a in enumerate(ASSUME, 1):
        T(d, (ax, ay), "%d." % i, F["body"], P["DIM"])
        T(d, (ax + 34, ay), a, F["body"], P["GRAY"])
        ay += 34
    y = max(y + 38, ay) + 14

    # --- ABO ---
    band("ABO blood type: what a child can and cannot be")
    T(d, (M, y), "A × B is the only pairing that can give all four child types.",
      F["body"], P["GREEN"])
    y += 40
    col_w = 716
    head_y = y
    for c in (0, 1):
        x0 = M + c * col_w
        T(d, (x0, head_y), "PARENTS", F["small"], P["DIM"])
        T(d, (x0 + 180, head_y), "CHILD CAN BE", F["small"], P["DIM"])
        T(d, (x0 + 430, head_y), "NEVER", F["small"], P["DIM"])
    y = head_y + 30
    half = (len(PAIRS) + 1) // 2
    for i, (a, b) in enumerate(PAIRS):
        x0 = M + (0 if i < half else 1) * col_w
        ry = y + (i % half) * 36
        T(d, (x0, ry), "%s × %s" % (a, b), F["label"], P["WHITE"])
        r = ABO["%sx%s" % (a, b)]
        T(d, (x0 + 180, ry), ", ".join(r["possible"]), F["body"], DOM)
        T(d, (x0 + 430, ry), ", ".join(r["impossible"]) or "nothing is ruled out",
          F["body"], REC if r["impossible"] else P["DIM"])
    y += half * 36 + 4
    T(d, (M, y), "A type does not fix a genotype: a type A parent is AA or AO, "
                 "which is why two type A parents can have a type O child.",
      F["body"], P["GRAY"])
    y += 46

    # --- X-linked ---
    band("X-linked recessive: carrier mother × unaffected father")
    STAT = {"unaffected": DOM, "carrier": DOM, "affected": REC}

    def xa(x, yy, allele, fill, base=None, sup=None):
        """X with a raised allele letter. Arial has no superscript H or h."""
        base = base or F["head"]
        sup = sup or F["small"]
        T(d, (x, yy), "X", base, fill)
        wx = d.textlength("X", font=base)
        T(d, (x + wx, yy - 7), allele, sup, fill)
        return wx + d.textlength(allele, font=sup)

    cw_, ch_, hw_, hh_ = 300, 104, 136, 58
    gx, gy = M, y
    T(d, (gx + 16, gy + 14), "mother", F["small"], P["DIM"])
    d.rectangle([gx, gy, gx + hw_, gy + hh_], fill=P["BAND"], outline=P["LINE"])
    for j, (head, who) in enumerate([("X" + XLR["dX"], "to daughters"),
                                     ("Y", "to sons")]):
        cx = gx + hw_ + j * cw_
        d.rectangle([cx, gy, cx + cw_, gy + hh_], fill=P["BAND"], outline=P["LINE"])
        if head == "Y":
            T(d, (cx + 20, gy + 14), "Y", F["head"], P["GRAY"])
            ww = d.textlength("Y", font=F["head"])
        else:
            ww = xa(cx + 20, gy + 14, XLR["dX"], P["GRAY"])
        T(d, (cx + 30 + ww, gy + 20), "father, " + who, F["small"], P["DIM"])
    for i, (dau, son) in enumerate(zip(XLR["daughters"], XLR["sons"])):
        cy = gy + hh_ + i * ch_
        d.rectangle([gx, cy, gx + hw_, cy + ch_], fill=P["BAND"], outline=P["LINE"])
        xa(gx + 40, cy + 34, dau["mom"], P["GRAY"])
        for j, kid in enumerate((dau, son)):
            cx = gx + hw_ + j * cw_
            d.rectangle([cx, cy, cx + cw_, cy + ch_], fill=P["CHIP"],
                        outline=P["LINE"])
            col = STAT[kid["status"]]
            wx = xa(cx + 24, cy + 18, kid["mom"], col)
            if j == 0:
                wx += xa(cx + 24 + wx, cy + 18, kid["dad"], col)
            else:
                T(d, (cx + 24 + wx, cy + 18), "Y", F["head"], col)
            T(d, (cx + 24, cy + 60),
              ("girl, " if j == 0 else "boy, ") + kid["status"], F["body"], col)
    y = gy + hh_ + 2 * ch_
    tx = gx + hw_ + 2 * cw_ + 40
    ty = gy + 6
    for line, col in [
            ("Of the daughters: half carriers, half neither.", P["GRAY"]),
            ("Of the sons: half affected, half unaffected.", P["GRAY"]),
            ("No daughter is affected here, because she would", P["GRAY"]),
            ("need the mutant allele from both parents.", P["GRAY"]),
            ("A son has one X, so one mutant allele shows.", DOM),
            ("The father gives his X only to daughters, so an", P["GRAY"]),
            ("X-linked trait never passes father to son.", P["GRAY"])]:
        fits(line, F["body"], W - M - tx, "X-linked note")
        T(d, (tx, ty), line, F["body"], col)
        ty += 34
    y = max(y, ty) + 24

    # --- common mistakes ---
    d.rounded_rectangle([M, y, W - M, y + 44 + len(MISTAKES) * 56], radius=14,
                        fill=P["CARD"], outline=P["RED"])
    my = y + 20
    T(d, (M + 24, my), "WHERE THE MARKS GO", F["label"], P["RED"])
    my += 36
    for head, body in MISTAKES:
        T(d, (M + 24, my), head, F["label"], P["RED"])
        T(d, (M + 24, my + 28), body, F["body"], P["GRAY"])
        fits(body, F["body"], CW - 48, "mistake body")
        my += 56
    y = y + 44 + len(MISTAKES) * 56 + 32

    chartkit.legend(d, M, y, [("Dominant phenotype or allele", DOM),
                              ("Recessive phenotype or allele", REC),
                              ("Formula", P["GREEN"]),
                              ("Common mistake", P["RED"])], P, F)
    y += 54
    y = chartkit.footer(d, W, H, y, P, F,
                        note="Squares and tables generated by the site's own "
                             "calculator code at build time.")

    img = chartkit.fit(img, y, d=d)
    out = _os.path.join(BUILD_DIR, "genetics-guide%s.png" % suffix())
    img.save(out)
    print("saved", out, img.size)
    print("verified: Aa x Aa %s genotype / %s phenotype, AaBb x AaBb %s, "
          "%d ABO pairings with A x B the only one giving all four, "
          "%d Hardy-Weinberg assumptions, X-linked daughters %s sons %s"
          % (ratio_str(SQ["AaxAa"]["geno"]), ratio_str(SQ["AaxAa"]["pheno"]),
             ratio_str(SQ["AaBbxAaBb"]["pheno"]), len(PAIRS), len(ASSUME),
             "/".join(d_["status"] for d_ in XLR["daughters"]),
             "/".join(s["status"] for s in XLR["sons"])))


draw()
